/* Real API and storage, synthetic native transcripts from session_search_server.py. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright');
(async()=>{
  const origin=process.env.SEARCH_TEST_URL||'http://127.0.0.1:8779';
  await fetch(origin+'/api/onboarding',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({deferred:true})});
  const browser=await chromium.launch({headless:true,channel:'msedge'});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(origin);await page.locator('#startup-loading').waitFor({state:'hidden'});
    await page.selectOption('#project','search-one');
    await page.waitForFunction(()=>projectReady&&!chatLoading);
    await page.getByRole('button',{name:'대화 검색',exact:true}).click();
    await page.locator('#session-search-status').filter({hasText:'3개 세션'}).waitFor();
    await page.getByRole('button',{name:'기록 새로 읽기'}).waitFor();
    await page.waitForFunction(()=>[...document.querySelectorAll('#session-search button')].find(b=>b.textContent==='기록 새로 읽기')?.disabled===false);
    const input=page.getByRole('searchbox',{name:'대화 검색어'});
    await input.fill('보안정책');await input.press('Enter');
    await page.waitForFunction(()=>document.querySelectorAll('.session-search-result').length===3);
    assert.equal(await page.locator('.session-search-result mark').count(),3);
    assert.equal(await page.evaluate(()=>window.searchUnsafe),undefined);
    await page.locator('.session-search-result').filter({hasText:'CODAST'}).getByRole('button',{name:'대화 보기'}).click();
    await page.locator('#session-search-preview .search-target').filter({hasText:'로컬첫기록'}).waitFor();
    await page.getByRole('button',{name:'이 채팅으로 이동'}).click();
    await page.locator('#session-search').waitFor({state:'hidden'});
    await page.locator('#messages .search-target').filter({hasText:'로컬첫기록'}).waitFor();
    assert.match(await page.locator('#page-number').textContent(),/^21/);
    await page.getByRole('button',{name:'대화 검색',exact:true}).click();
    await input.fill('코덱스첫기록');await input.press('Enter');
    await page.locator('.session-search-result').filter({hasText:'코덱스첫기록'}).getByRole('button',{name:'대화 보기'}).click();
    await page.locator('#session-search-preview .search-target').filter({hasText:'코덱스첫기록'}).waitFor();
    await page.getByRole('button',{name:'뒤 대화',exact:true}).click();
    await page.locator('#session-search-preview').filter({hasText:'후속 Codex 24'}).waitFor();
    await page.getByRole('button',{name:'앞 대화',exact:true}).click();
    await page.locator('#session-search-preview .search-target').filter({hasText:'코덱스첫기록'}).waitFor();
    await input.fill('클로드첫기록');await input.press('Enter');
    await page.locator('.session-search-result').filter({hasText:'클로드첫기록'}).getByRole('button',{name:'대화 보기'}).click();
    await page.locator('#session-search-preview .search-target').filter({hasText:'클로드첫기록'}).waitFor();
    fs.mkdirSync('work/session-search-browser',{recursive:true});
    await page.screenshot({path:'work/session-search-browser/search-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.locator('#session-search').evaluate(n=>n.scrollWidth<=n.clientWidth+1),true);
    await page.screenshot({path:'work/session-search-browser/search-narrow.png',fullPage:true});
    await page.getByRole('button',{name:'이 세션 연결하기'}).click();
    await page.getByRole('heading',{name:'세션 내용 불러오기'}).waitFor();
    assert.match(await page.locator('.native-thread-preview').textContent(),/후속 Claude/);
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:1440,height:1000});
    await page.selectOption('#project','search-two');await page.waitForFunction(()=>projectReady&&!chatLoading);
    await page.getByRole('button',{name:'대화 검색',exact:true}).click();
    await input.fill('보안정책');await input.press('Enter');
    await page.locator('#session-search-results').filter({hasText:'일치하는 대화가 없습니다'}).waitFor();
    assert.equal(await page.locator('.session-search-result').count(),0);
    assert.deepEqual(errors,[]);
    console.log('PASS: CODAST/Codex/Claude full history, matching message navigation, pagination, project scope, XSS and narrow layout');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
